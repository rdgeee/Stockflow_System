import { Router } from "express";
import authRoutes from "./auth.routes.js";
import usersRoutes from "./users.routes.js";
import { rolesRouter, branchesRouter, productsRouter, suppliersRouter, vehiclesRouter, routesRouter } from "./simple.routes.js";
import inventoryRoutes from "./inventory.routes.js";
import transfersRoutes from "./transfers.routes.js";
import purchaseOrdersRoutes from "./purchaseOrders.routes.js";
import shipmentsRoutes from "./shipments.routes.js";
import alertsRoutes from "./alerts.routes.js";
import auditLogsRoutes from "./auditLogs.routes.js";
import dashboardRoutes from "./dashboard.routes.js";

const api = Router();
api.get("/health", (_req, res) => res.json({ status: "ok", time: new Date().toISOString() }));
api.use("/auth", authRoutes);
api.use("/users", usersRoutes);
api.use("/roles", rolesRouter);
api.use("/branches", branchesRouter);
api.use("/products", productsRouter);
api.use("/suppliers", suppliersRouter);
api.use("/inventory", inventoryRoutes);
api.use("/transfers", transfersRoutes);
api.use("/purchase-orders", purchaseOrdersRoutes);
api.use("/vehicles", vehiclesRouter);
api.use("/routes", routesRouter);
api.use("/shipments", shipmentsRoutes);
api.use("/low-stock-alerts", alertsRoutes);
api.use("/audit-logs", auditLogsRoutes);
api.use("/dashboard", dashboardRoutes);
export default api;
